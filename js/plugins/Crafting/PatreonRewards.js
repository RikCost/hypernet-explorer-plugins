  // Deliberately prints no coordinates: they are not in the database, and the
  // report is not the place to leak them. It reports the square the party is
  // standing on, and nothing about anybody else's.
  // i18n-ignore-start: developer console report, never shown to a player
  PluginManager.registerCommand(PLUGIN_NAME, "report", () => {
    for (const p of PATRONS) {
      log(`${p.name} (${p.id}) · ${p.biome || "?"} · vault ${VAULT_BIOME} · ` +
        `${p.planetName} in ${p.galaxy} (${systemNameFor(p)})`);
    }
    log(`${PATRONS.length} patrons, ${RESERVED} reserved slots waiting for a name`);
    const here = currentWorldCoords();
    const rec = here ? patronRecordAtWorld(here.x, here.y) : null;
    log(rec
      ? `this square belongs to ${rec.patron.name}: hatch at ${rec.mapCoordinates.join(",")}`
      : "this square belongs to no patron");
  });
